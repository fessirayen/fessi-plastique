const STORAGE_KEY = "fessi-plastique-lang";

function applyLang(lang) {
  const dict = I18N[lang] || I18N.fr;
  document.documentElement.lang = lang;
  document.title = dict["meta.title"];
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", dict["meta.desc"]);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (dict[key] !== undefined) el.setAttribute("alt", dict[key]);
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", String(on));
  });
}

const saved = (() => {
  try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
})();
applyLang(saved === "en" ? "en" : "fr");

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    const lang = btn.dataset.lang;
    applyLang(lang);
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* private mode */ }
  });
});

const REVEAL_SELECTOR = ".sec-head, .split-fig, .split-body, .pair, .spec, .chips, .note, .contact-cards, .contact-actions, .prod-card, .test-card";
const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const targets = Array.from(document.querySelectorAll(REVEAL_SELECTOR));

if (reduced || !("IntersectionObserver" in window)) {
  targets.forEach((el) => el.classList.add("is-in"));
} else {
  targets.forEach((el) => {
    const siblings = Array.from(el.parentElement.children).filter((c) => c.matches(REVEAL_SELECTOR));
    el.style.setProperty("--rd", `${siblings.indexOf(el) * 90}ms`);
    el.classList.add("reveal");
  });
  const io = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add("is-in");
      io.unobserve(entry.target);
    }
  }, { rootMargin: "0px 0px -10% 0px", threshold: 0.12 });
  targets.forEach((el) => io.observe(el));
}

const head = document.querySelector(".site-head");
if (head && !reduced) {
  const bar = document.createElement("span");
  bar.className = "head-prog";
  bar.setAttribute("aria-hidden", "true");
  head.appendChild(bar);
  let queued = false;
  const paint = () => {
    const span = document.documentElement.scrollHeight - window.innerHeight;
    bar.style.transform = `scaleX(${span > 0 ? Math.min(1, window.scrollY / span) : 0})`;
    queued = false;
  };
  window.addEventListener("scroll", () => {
    if (queued) return;
    queued = true;
    requestAnimationFrame(paint);
  }, { passive: true });
  window.addEventListener("resize", paint);
  paint();
}

document.querySelectorAll(".prod-toggle").forEach((btn) => {
  btn.addEventListener("click", () => {
    const open = btn.getAttribute("aria-expanded") === "true";
    btn.setAttribute("aria-expanded", String(!open));
    btn.closest(".prod-card").classList.toggle("is-open", !open);
  });
});

const stats = document.querySelector(".stats");
if (stats) {
  const runCounters = () => {
    stats.querySelectorAll("[data-count]").forEach((el) => {
      const target = Number(el.dataset.count);
      const suffix = el.dataset.suffix || "";
      if (reduced) { el.textContent = target + suffix; return; }
      const start = performance.now();
      const tick = (now) => {
        const p = Math.min(1, (now - start) / 1100);
        el.textContent = Math.round(target * (1 - Math.pow(1 - p, 3))) + suffix;
        if (p < 1) requestAnimationFrame(tick);
      };
      requestAnimationFrame(tick);
    });
  };
  if (reduced || !("IntersectionObserver" in window)) {
    runCounters();
  } else {
    const so = new IntersectionObserver((entries) => {
      if (!entries.some((e) => e.isIntersecting)) return;
      so.disconnect();
      runCounters();
    }, { threshold: 0.3 });
    so.observe(stats);
  }
}
